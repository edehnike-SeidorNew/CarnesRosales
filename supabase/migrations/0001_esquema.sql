-- Correr UNA vez en Supabase: SQL Editor > New query > pegar todo > Run.
-- Va en una transacción: si algo falla, no queda nada a medias.

begin;

-- ---------------------------------------------------------------------------
-- Tipos
-- ---------------------------------------------------------------------------
create type public.tipo_movimiento as enum ('saldo_inicial', 'venta', 'pago');
create type public.medio_pago as enum ('efectivo', 'mercado_pago', 'transferencia');

-- ---------------------------------------------------------------------------
-- Clientes (hoja de clientes de la planilla)
-- ---------------------------------------------------------------------------
create table public.clientes (
  id              uuid primary key default gen_random_uuid(),
  -- Número de la planilla. Los clientes nuevos siguen la numeración sola.
  numero          integer generated by default as identity unique,
  nombre_fantasia text not null check (btrim(nombre_fantasia) <> ''),
  titular         text not null default '',
  direccion       text not null default '',
  localidad       text not null default '',
  cuit            text not null default '',
  contacto        text not null default '',
  observaciones   text not null default '',
  created_at      timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Productos (cortes). Catálogo para que "Picada" y "PICADA" sean lo mismo
-- al sumar kilos vendidos por corte.
-- ---------------------------------------------------------------------------
create table public.productos (
  id         uuid primary key default gen_random_uuid(),
  nombre     text not null check (btrim(nombre) <> ''),
  created_at timestamptz not null default now()
);

create unique index productos_nombre_unico on public.productos (lower(nombre));

-- ---------------------------------------------------------------------------
-- Movimientos de la cuenta corriente: saldo inicial, ventas (remitos) y pagos.
-- El saldo NUNCA se guarda: siempre sale de sumar los movimientos.
-- ---------------------------------------------------------------------------
create table public.movimientos (
  id          uuid primary key default gen_random_uuid(),
  -- Orden de carga: desempata los movimientos de un mismo día.
  orden       bigint generated always as identity unique,
  cliente_id  uuid not null references public.clientes (id) on delete restrict,
  fecha       date not null,
  tipo        public.tipo_movimiento not null,
  -- N° de remito / factura (ventas) o de recibo (pagos).
  comprobante text not null default '',
  -- Sólo para saldo inicial y pagos. El importe de una venta es la suma de sus ítems.
  importe     numeric(14, 2),
  -- Sólo para pagos. Null = sin especificar (pagos anteriores a registrar este dato).
  medio_pago  public.medio_pago,
  created_at  timestamptz not null default now(),

  constraint movimientos_importe_segun_tipo check (
    (tipo = 'venta' and importe is null)
    or (tipo = 'pago' and importe is not null and importe > 0)
    or (tipo = 'saldo_inicial' and importe is not null)
  ),
  constraint movimientos_medio_solo_en_pagos check (medio_pago is null or tipo = 'pago')
);

create index movimientos_por_cliente on public.movimientos (cliente_id, fecha, orden);
create index movimientos_por_fecha on public.movimientos (fecha, orden);
-- Un solo saldo inicial por cliente.
create unique index movimientos_un_saldo_inicial on public.movimientos (cliente_id) where tipo = 'saldo_inicial';

-- ---------------------------------------------------------------------------
-- Ítems de cada venta: producto, kilos y precio por kilo.
-- ---------------------------------------------------------------------------
create table public.movimiento_items (
  id            uuid primary key default gen_random_uuid(),
  movimiento_id uuid not null references public.movimientos (id) on delete cascade,
  -- Posición del renglón dentro del remito.
  orden         smallint not null check (orden > 0),
  producto_id   uuid not null references public.productos (id) on delete restrict,
  kilos         numeric(10, 3) not null check (kilos > 0),
  precio        numeric(12, 2) not null check (precio > 0),
  subtotal      numeric(14, 2) generated always as (round(kilos * precio, 2)) stored,

  unique (movimiento_id, orden)
);

create index movimiento_items_por_producto on public.movimiento_items (producto_id);

-- ---------------------------------------------------------------------------
-- Vistas de consulta (respetan los permisos de quien consulta)
-- ---------------------------------------------------------------------------
-- Cuánto suma (+) o resta (-) cada movimiento al saldo del cliente.
create view public.movimientos_importes with (security_invoker = true) as
select
  m.id,
  m.cliente_id,
  m.fecha,
  m.orden,
  m.tipo,
  m.comprobante,
  m.medio_pago,
  case m.tipo
    when 'venta' then coalesce((select sum(i.subtotal) from public.movimiento_items i where i.movimiento_id = m.id), 0)
    when 'pago' then -m.importe
    else m.importe
  end as efecto
from public.movimientos m;

-- Saldo adeudado de cada cliente.
create view public.saldos_clientes with (security_invoker = true) as
select
  c.id as cliente_id,
  c.numero,
  c.nombre_fantasia,
  coalesce(sum(mi.efecto), 0)::numeric(14, 2) as saldo
from public.clientes c
left join public.movimientos_importes mi on mi.cliente_id = c.id
group by c.id, c.numero, c.nombre_fantasia;

-- ---------------------------------------------------------------------------
-- Alta de una venta completa (remito + ítems) en una sola operación:
-- o se guarda todo, o no se guarda nada. Crea el producto si no existía.
-- p_items: [{"detalle": "Picada", "kilos": 11.8, "precio": 13000}, ...]
-- ---------------------------------------------------------------------------
create function public.registrar_venta(
  p_cliente_id  uuid,
  p_fecha       date,
  p_comprobante text,
  p_items       jsonb
) returns uuid
language plpgsql
set search_path = public
as $$
declare
  v_movimiento uuid;
  v_item       jsonb;
  v_producto   uuid;
  v_nombre     text;
  v_posicion   smallint := 0;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La venta necesita al menos un producto';
  end if;

  insert into movimientos (cliente_id, fecha, tipo, comprobante)
  values (p_cliente_id, p_fecha, 'venta', coalesce(btrim(p_comprobante), ''))
  returning id into v_movimiento;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_posicion := v_posicion + 1;
    v_nombre := regexp_replace(btrim(coalesce(v_item ->> 'detalle', '')), '\s+', ' ', 'g');
    if v_nombre = '' then
      raise exception 'El producto % no tiene detalle', v_posicion;
    end if;

    select id into v_producto from productos where lower(nombre) = lower(v_nombre);
    if v_producto is null then
      insert into productos (nombre) values (v_nombre) returning id into v_producto;
    end if;

    insert into movimiento_items (movimiento_id, orden, producto_id, kilos, precio)
    values (v_movimiento, v_posicion, v_producto, (v_item ->> 'kilos')::numeric, (v_item ->> 'precio')::numeric);
  end loop;

  return v_movimiento;
end;
$$;

-- ---------------------------------------------------------------------------
-- Seguridad: sólo usuarios con sesión iniciada. Sin login no se lee ni escribe nada.
-- ---------------------------------------------------------------------------
alter table public.clientes enable row level security;
alter table public.productos enable row level security;
alter table public.movimientos enable row level security;
alter table public.movimiento_items enable row level security;

create policy "usuarios con sesion" on public.clientes for all to authenticated using (true) with check (true);
create policy "usuarios con sesion" on public.productos for all to authenticated using (true) with check (true);
create policy "usuarios con sesion" on public.movimientos for all to authenticated using (true) with check (true);
create policy "usuarios con sesion" on public.movimiento_items for all to authenticated using (true) with check (true);

revoke all on public.clientes, public.productos, public.movimientos, public.movimiento_items from anon;
revoke all on public.movimientos_importes, public.saldos_clientes from anon;
revoke all on function public.registrar_venta(uuid, date, text, jsonb) from public, anon;
grant execute on function public.registrar_venta(uuid, date, text, jsonb) to authenticated;

commit;
